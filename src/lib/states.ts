export const STATE_CODES = new Set(STATES.map((s) => s.code));

export function stateName(code: string): string {
  return STATES.find((s) => s.code === code)?.name ?? code;
}

/** Accepts a code ("HR") or a name ("haryana") and returns the code, or null. */
export function findState(text: string): string | null {
  const t = text.trim().toLowerCase();
  if (!t) return null;
  const hit = STATES.find((s) => s.code.toLowerCase() === t || s.name.toLowerCase() === t);
  return hit ? hit.code : null;
}
